import fs from 'fs';
import path from 'path';

const productsDir = path.resolve(process.cwd(), 'public', 'assets', 'products');
const outFile = path.resolve(process.cwd(), 'src', 'data', 'productFileMap.ts');
const catalogPath = path.resolve(process.cwd(), 'src', 'data', 'catalog.ts');

function slugify(name) {
  return name
    .toLowerCase()
    .replace(/\.[^.]+$/, '')
    .replace(/\s+/g, '-')
    .replace(/[^a-z0-9\-]/g, '-')
    .replace(/-+/g, '-')
    .replace(/^-|-$/g, '');
}

const files = fs.readdirSync(productsDir).filter(f => fs.statSync(path.join(productsDir, f)).isFile());
// build lookup by lowercase filename -> actual filename
const filesLowerMap = {};
for (const f of files) filesLowerMap[f.toLowerCase()] = f;

const catalog = fs.readFileSync(catalogPath, 'utf8');
const slugRegex = /p\([^,]+,\s*"([a-z0-9\-]+)"/g;
let match; const productSlugs = [];
while((match = slugRegex.exec(catalog))) productSlugs.push(match[1]);

const imageExts = ['.jpeg', '.jpg', '.png', '.webp', '.gif'];
const map = {};

for (const slug of productSlugs) {
  // try exact slug + ext
  let found = null;
  for (const ext of imageExts) {
    const candidate = `${slug}${ext}`;
    const candLower = candidate.toLowerCase();
    if (filesLowerMap[candLower]) { found = filesLowerMap[candLower]; break; }
  }
  if (found) { map[slug] = found; continue; }

  // try filenames where slug is prefix
  for (const f of files) {
    const key = slugify(f);
    if (key === slug) { found = f; break; }
  }
  if (found) { map[slug] = found; continue; }

  // fuzzy token overlap
  const tokenize = s => s.split(/[-_\s]+/).filter(Boolean);
  const slugTokens = new Set(tokenize(slug));
  let best = null; let bestScore = 0;
  for (const f of files) {
    const key = slugify(f);
    const keyTokens = new Set(tokenize(key));
    let score = 0;
    for (const t of slugTokens) if (keyTokens.has(t)) score++;
    if (score > bestScore) { bestScore = score; best = f; }
  }
  if (best && bestScore > 0) map[slug] = best;
}

const content = `// This file is generated by scripts/generate-product-map-deterministic.js\nexport const productFileMap = ${JSON.stringify(map, null, 2)} as Record<string,string>;\n`;
fs.writeFileSync(outFile, content, 'utf8');
console.log('Wrote', outFile, 'with', Object.keys(map).length, 'entries');
