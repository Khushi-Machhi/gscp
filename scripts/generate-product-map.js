import fs from 'fs';
import path from 'path';

const productsDir = path.resolve(process.cwd(), 'public', 'assets', 'products');
const outFile = path.resolve(process.cwd(), 'src', 'data', 'productFileMap.ts');

function slugify(name) {
  return name
    .toLowerCase()
    .replace(/\.[^.]+$/, '')
    .replace(/\s+/g, '-')
    .replace(/[^a-z0-9\-]/g, '-')
    .replace(/-+/g, '-')
    .replace(/^-|-$/g, '');
}

const files = fs.readdirSync(productsDir).filter(f => fs.statSync(path.join(productsDir, f)).isFile());
const map = {};
const imageExts = ['.jpeg', '.jpg', '.png', '.webp', '.gif'];
for (const f of files) {
  const key = slugify(f);
  const ext = path.extname(f).toLowerCase();
  if (!map[key]) {
    map[key] = f;
  } else {
    // prefer image extensions over other types (e.g., mp4, heic)
    const existingExt = path.extname(map[key]).toLowerCase();
    const existingIsImage = imageExts.includes(existingExt);
    const newIsImage = imageExts.includes(ext);
    if (!existingIsImage && newIsImage) {
      map[key] = f;
    }
    // if both are images or both not images, keep the first
  }
}

// Try to read product slugs from catalog.ts to add best-match mappings
const catalogPath = path.resolve(process.cwd(), 'src', 'data', 'catalog.ts');
if (fs.existsSync(catalogPath)) {
  const catalog = fs.readFileSync(catalogPath, 'utf8');
  const slugRegex = /p\(presets\.[a-zA-Z0-9_]+,\s*"([a-z0-9\-]+)"/g;
  let match;
  const productSlugs = [];
  while ((match = slugRegex.exec(catalog))) productSlugs.push(match[1]);

  const tokenize = s => s.split(/[-_\s]+/).filter(Boolean);

  for (const slug of productSlugs) {
    if (map[slug]) continue; // exact match exists
    // find best candidate by token overlap
    const slugTokens = new Set(tokenize(slug));
    let best = null;
    let bestScore = 0;
    for (const key of Object.keys(map)) {
      const keyTokens = new Set(tokenize(key));
      let score = 0;
      for (const t of slugTokens) if (keyTokens.has(t)) score++;
      if (score > bestScore) {
        bestScore = score;
        best = key;
      }
    }
    if (best && bestScore > 0) {
      map[slug] = map[best];
    }
  }
}

// Prefer slugified filenames when a slugified copy exists (e.g., "assembly-lab.jpeg")
for (const key of Object.keys(map)) {
  const candidate = `${key}${path.extname(map[key])}`; // keep same extension
  const candidatePath = path.join(productsDir, candidate);
  if (fs.existsSync(candidatePath)) {
    map[key] = candidate;
  }
}

const content = `// This file is generated by scripts/generate-product-map.js\nexport const productFileMap = ${JSON.stringify(map, null, 2)} as Record<string,string>;\n`;

fs.writeFileSync(outFile, content, 'utf8');
console.log('Wrote', outFile, 'with', Object.keys(map).length, 'entries');
